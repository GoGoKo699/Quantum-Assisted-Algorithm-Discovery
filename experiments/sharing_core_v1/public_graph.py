def verify_source():
    b=json.dumps(source_object(),indent=4).encode()
    sha=hashlib.sha1(b'blob '+str(len(b)).encode()+b'\0'+b).hexdigest()
    if sha!='0a6fdaa6432a55b7c49001bd83531835efc6a1af':
        raise AssertionError((len(b),sha,'source byte reconstruction mismatch'))
    return dict(bytes=len(b),git_blob_sha=sha)

def load_graph():
    source=source_object(); ns=source['nodes']; classes={}
    for name,n in ns.items():
        c=n['eclass']; children=tuple(ns[x]['eclass'] for x in n['children'])
        classes.setdefault(c,[]).append(Node(name, int(round(1000*n['cost'])), children))
    return Graph({c:tuple(v) for c,v in classes.items()}, tuple(source['root_eclasses']))

def remove_direct_self_dependencies(g):
    classes={c:tuple(n for n in ns if c not in n.children) for c,ns in g.classes.items()}
    if any(not ns for ns in classes.values()):
        raise ValueError('General unproductive-class pruning not implemented in this adapter.')
    return Graph(classes,g.roots).restrict_reachable()

